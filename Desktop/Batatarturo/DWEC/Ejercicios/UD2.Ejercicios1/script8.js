let color = prompt("Dime un color");



switch(color) {

    case "rojo":
        document.write("Has elegido el rojo, gran opción")
    break;

    case "verde":
        document.write("El verde es el elegido")
    break;

    case "azul":
        document.write("Te quedas con el azul, genial ")
    break;

default:
    document.write("No coincide con los colores")
}
