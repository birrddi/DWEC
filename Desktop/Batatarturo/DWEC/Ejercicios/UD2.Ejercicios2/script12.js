let nota = prompt("Dime tu nota");

if(nota < 5) {
    document.write("Has suspendido")
}

if(nota >= 5 && nota <= 6) {
    document.write("Aprobado")
}


if(nota >= 7 && nota <= 8) {
    document.write("Bueno un Notable")
}


if(nota >= 9 && nota <= 10) {
        document.write("Es un sobresaliente")
}

